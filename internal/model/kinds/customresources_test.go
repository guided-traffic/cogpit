// customCase is one directory of testdata/customresources: a definition (crd.yaml) and objects of
// its kind (every other YAML file).
type customCase struct {
	name    string
	dir     string
	crd     testCase
	objects []testCase
}

func loadCustomCases(t testing.TB) []customCase {
	t.Helper()
	dirs, err := filepath.Glob(filepath.Join("testdata", "customresources", "*"))
	if err != nil || len(dirs) == 0 {
		t.Fatalf("no custom resource testdata: %v", err)
	}
	var out []customCase
	for _, dir := range dirs {
		cc := customCase{name: filepath.Base(dir), dir: dir}
		found := false
		for _, c := range loadCases(t, filepath.Join("customresources", cc.name)) {
			if c.name == "crd" {
				cc.crd, found = c, true
				continue
			}
			cc.objects = append(cc.objects, c)
		}
		if !found {
			t.Fatalf("%s: no crd.yaml", dir)
		}
		out = append(out, cc)
	}
	return out
}

// profileGolden is what a definition becomes: the profile's identity and columns, or the error.
type profileGolden struct {
	Error      string         `json:"error,omitempty"`
	Key        string         `json:"key,omitempty"`
	Group      string         `json:"group,omitempty"`
	Version    string         `json:"version,omitempty"`
	Resource   string         `json:"resource,omitempty"`
	Kind       string         `json:"kind,omitempty"`
	Title      string         `json:"title,omitempty"`
	Namespaced bool           `json:"namespaced,omitempty"`
	Columns    []model.Column `json:"columns,omitempty"`
	Fields     []string       `json:"fields,omitempty"`
}

func checkGolden(t *testing.T, path string, got []byte) {
	t.Helper()
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/model/kinds/ -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from the golden file:\n%s", path, lineDiff(string(want), string(got)))
	}
}

// TestCustomGolden builds the profile of every synthetic definition and renders its objects:
// profile.golden.json holds the profile (or why there is none), <object>.golden.json each row,
// fields and drawer. Run with -update to rewrite them, then read the diff.
func TestCustomGolden(t *testing.T) {
	for _, cc := range loadCustomCases(t) {
		t.Run(cc.name, func(t *testing.T) {
			k, err := kinds.ParseCRD(cc.crd.obj)
			var pg profileGolden
			var p *model.KindProfile
			if err != nil {
				pg.Error = err.Error()
			} else {
				p = k.Profile()
				pg = profileGolden{Key: p.Key, Group: p.Group, Version: p.Version, Resource: p.Resource,
					Kind: p.Kind, Title: p.Title, Namespaced: p.Namespaced, Columns: p.Columns}
				for name := range p.Fields {
					pg.Fields = append(pg.Fields, name)
				}
				slices.Sort(pg.Fields)
			}
			checkGolden(t, filepath.Join(cc.dir, "profile.golden.json"), encode(t, pg))
			if p == nil {
				if len(cc.objects) > 0 {
					t.Fatalf("objects of a kind without a profile")
				}
				return
			}
			for _, c := range cc.objects {
				t.Run(c.name, func(t *testing.T) {
					checkGolden(t, strings.TrimSuffix(c.path, ".yaml")+".golden.json", encode(t, render(t, p, c.obj)))
				})
			}
		})
		goldens, _ := filepath.Glob(filepath.Join(cc.dir, "*.golden.json"))
		for _, g := range goldens {
			if filepath.Base(g) == "profile.golden.json" {
				continue
			}
			if _, err := os.Stat(strings.TrimSuffix(g, ".golden.json") + ".yaml"); err != nil {
				t.Errorf("orphan golden %s", g)
			}
		}
	}
}

func customProfile(t testing.TB, name string) *model.KindProfile {
	t.Helper()
	for _, cc := range loadCustomCases(t) {
		if cc.name == name {
			k, err := kinds.ParseCRD(cc.crd.obj)
			if err != nil {
				t.Fatalf("%s: %v", name, err)
			}
			return k.Profile()
		}
	}
	t.Fatalf("no custom case %s", name)
	return nil
}

func columnIDs(p *model.KindProfile, hidden bool) []string {
	var ids []string
	for _, c := range p.Columns {
		if c.Hidden == hidden {
			ids = append(ids, c.ID)
		}
	}
	return ids
}

// TestCustomColumns states the column rules outright, so that a golden regenerated by mistake
// cannot change them.
func TestCustomColumns(t *testing.T) {
	tests := []struct {
		name            string
		visible, hidden []string
		title, version  string
	}{
		// Captured: Lens shows cert-manager's Order with Name, Namespace, State, Age. Issuer and
		// Reason (priority 1) are hidden; the Age printer column takes the place of Cogpit's own.
		{"order", []string{"name", "namespace", "state", "age"}, []string{"issuer", "reason"}, "Order", "v1"},
		{"gateway", []string{"name", "namespace", "class", "address", "programmed", "age"}, nil, "Gateway", "v1"},
		// Cluster-scoped: no Namespace column; a printer column named Name gets another id; no Age
		// printer column, so Cogpit's own Age comes last.
		{"widget", []string{"name", "name2", "replicas", "ratio", "enabled", "lastSync", "ready", "selector", "age"}, []string{"ipAddress"}, "Widget", "v1"},
		// The highest served version and its printer columns, not the storage version's.
		{"backup", []string{"name", "namespace", "phase", "size", "age"}, []string{"schedule"}, "Backup", "v1beta1"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			p := customProfile(t, tt.name)
			if got := columnIDs(p, false); !slices.Equal(got, tt.visible) {
				t.Errorf("visible columns %v, want %v", got, tt.visible)
			}
			if got := columnIDs(p, true); !slices.Equal(got, tt.hidden) {
				t.Errorf("hidden columns %v, want %v", got, tt.hidden)
			}
			if p.Title != tt.title || p.Version != tt.version {
				t.Errorf("title %q version %q, want %q %q", p.Title, p.Version, tt.title, tt.version)
			}
			checkProfileShape(t, p)
		})
	}
}

// checkProfileShape is TestBuiltinProfiles' check for a custom profile.
func checkProfileShape(t *testing.T, p *model.KindProfile) {
	t.Helper()
	if !strings.Contains(p.Key, ".") || p.Key != p.Resource+"."+p.Group {
		t.Errorf("key %q: want <plural>.<group>", p.Key)
	}
	if p.Cells == nil || p.Detail == nil || len(p.Columns) == 0 || p.Columns[0].ID != "name" {
		t.Errorf("%s: Cells, Detail or the name column missing", p.Key)
	}
	seen := map[string]bool{}
	for _, c := range p.Columns {
		if !lowerCamel.MatchString(c.ID) || seen[c.ID] || c.Title == "" {
			t.Errorf("%s: bad or duplicate column %+v", p.Key, c)
		}
		seen[c.ID] = true
	}
	if p.Namespaced && !seen["namespace"] {
		t.Errorf("%s: namespaced but no namespace column", p.Key)
	}
	for name := range p.Fields {
		if !lowerCamel.MatchString(name) {
			t.Errorf("%s: field %q is not lowerCamelCase", p.Key, name)
		}
	}
}

