func TestParseCRDErrors(t *testing.T) {
	base := func() *unstructured.Unstructured {
		return &unstructured.Unstructured{Object: map[string]any{
			"spec": map[string]any{
				"group": "example.com", "scope": "Namespaced",
				"names":    map[string]any{"plural": "things", "kind": "Thing"},
				"versions": []any{map[string]any{"name": "v1", "served": true}},
			},
			"status": map[string]any{"conditions": []any{map[string]any{"type": "Established", "status": "True"}}},
		}}
	}
	if k, err := kinds.ParseCRD(base()); err != nil || k.Key() != "things.example.com" || !k.Namespaced {
		t.Fatalf("base: %+v, %v", k, err)
	}
	tests := []struct {
		name   string
		mutate func(m map[string]any)
		want   error
	}{
		{"not established", func(m map[string]any) { m["status"] = nil }, kinds.ErrNotEstablished},
		{"established false", func(m map[string]any) {
			m["status"] = map[string]any{"conditions": []any{map[string]any{"type": "Established", "status": "False"}}}
		}, kinds.ErrNotEstablished},
		{"no served version", func(m map[string]any) {
			m["spec"].(map[string]any)["versions"] = []any{map[string]any{"name": "v1", "served": false}}
		}, kinds.ErrNoServedVersion},
		{"group without a dot", func(m map[string]any) { m["spec"].(map[string]any)["group"] = "pods" }, kinds.ErrInvalidDefinition},
		{"upper-case plural", func(m map[string]any) {
			m["spec"].(map[string]any)["names"] = map[string]any{"plural": "Things", "kind": "Thing"}
		}, kinds.ErrInvalidDefinition},
		{"kind with a space", func(m map[string]any) {
			m["spec"].(map[string]any)["names"] = map[string]any{"plural": "things", "kind": "A Thing"}
		}, kinds.ErrInvalidDefinition},
		{"no spec", func(m map[string]any) { delete(m, "spec") }, kinds.ErrInvalidDefinition},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			obj := base()
			tt.mutate(obj.Object)
			if _, err := kinds.ParseCRD(obj); !errors.Is(err, tt.want) {
				t.Errorf("err %v, want %v", err, tt.want)
			}
		})
	}
	if _, err := kinds.ParseCRD(nil); !errors.Is(err, kinds.ErrInvalidDefinition) {
		t.Errorf("nil: %v", err)
	}
}

// TestCustomKindEqual: a definition update that changes nothing the view shows keeps the profile;
// a new served version or printer column does not.
func TestCustomKindEqual(t *testing.T) {
	var crd *unstructured.Unstructured
	for _, cc := range loadCustomCases(t) {
		if cc.name == "backup" {
			crd = cc.crd.obj
		}
	}
	a, err := kinds.ParseCRD(crd)
	if err != nil {
		t.Fatal(err)
	}
	status := crd.DeepCopy()
	status.Object["status"].(map[string]any)["storedVersions"] = []any{"v1alpha1", "v1beta1"}
	if b, _ := kinds.ParseCRD(status); !a.Equal(b) {
		t.Error("a status change made a different kind")
	}
	served := crd.DeepCopy()
	versions := served.Object["spec"].(map[string]any)["versions"].([]any)
	versions[2].(map[string]any)["served"] = true
	b, err := kinds.ParseCRD(served)
	if err != nil || a.Equal(b) || b.Version != "v1" || b.Columns[0].Name != "State" {
		t.Errorf("serving v1: %+v, %v; want version v1 with its columns", b, err)
	}
}

// TestJSONPathsRefused: printer column paths a simple path never needs are not evaluated, so the
// column stays empty instead of costing time or changing evaluation state.
func TestJSONPathsRefused(t *testing.T) {
	obj := &unstructured.Unstructured{Object: map[string]any{
		"metadata": map[string]any{"name": "x"},
		"spec":     map[string]any{"a": []any{"one", "two"}, "b": "bee"},
	}}
	for _, tt := range []struct {
		path, want string
	}{
		{".spec.b", "bee"},
		{".spec.a[0]", "one"},
		{".spec.a[*]", "one"},
		{`.spec.a[?(@=="two")]`, "two"},
		{".spec.b}{.spec.a[0]", ""},               // leaves the braces
		{".spec.a}{range .spec.a[*]}{@}{end", ""}, // range and end
		{"..a[*][*]", ""},                         // three fan-outs
		{".spec." + strings.Repeat("x", 600), ""}, // too long
		{".spec.a[", ""},                          // does not parse
		{".spec.a[0:1:0]", ""},                    // a step of zero: an evaluation error
		{".spec.a[5]", ""},                        // out of range: an evaluation error
		{".spec.b.c", ""},                         // missing
	} {
		crd := &unstructured.Unstructured{Object: map[string]any{
			"spec": map[string]any{
				"group": "example.com", "scope": "Cluster",
				"names": map[string]any{"plural": "things", "kind": "Thing"},
				"versions": []any{map[string]any{"name": "v1", "served": true, "additionalPrinterColumns": []any{
					map[string]any{"name": "Value", "type": "string", "jsonPath": tt.path},
				}}},
			},
			"status": map[string]any{"conditions": []any{map[string]any{"type": "Established", "status": "True"}}},
		}}
		k, err := kinds.ParseCRD(crd)
		if err != nil {
			t.Fatalf("%s: %v", tt.path, err)
		}
		p := k.Profile()
		row := model.BuildRow(p, "test", obj)
		if got := row.Cells[p.ColumnIndex("value")].Text; got != tt.want {
			t.Errorf("%s: %q, want %q", tt.path, got, tt.want)
		}
	}
}

// TestCustomRowsConcurrently builds rows of one profile from many goroutines: views, commands and
// agents do, and a jsonpath.JSONPath keeps evaluation state. Run with -race.
func TestCustomRowsConcurrently(t *testing.T) {
	p := customProfile(t, "widget")
	var objs []*unstructured.Unstructured
	for _, cc := range loadCustomCases(t) {
		if cc.name == "widget" {
			for _, c := range cc.objects {
				objs = append(objs, c.obj)
			}
		}
	}
	want := make([]model.Row, len(objs))
	for i, o := range objs {
		want[i] = model.BuildRow(p, "test", o)
	}
	var wg sync.WaitGroup
	errs := make(chan error, 8)
	for g := range 8 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for n := range 200 {
				i := (g + n) % len(objs)
				got := model.BuildRow(p, "test", objs[i])
				if !slices.EqualFunc(got.Cells, want[i].Cells, sameCell) {
					errs <- fmt.Errorf("row %d differs under concurrency", i)
					return
				}
				_ = p.Detail(objs[i])
			}
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
}

// FuzzParseCRD feeds arbitrary JSON as a definition: ParseCRD and the profile it builds never
// panic, and the profile's rows have one cell per column for every recorded object.
func FuzzParseCRD(f *testing.F) {
	cases := loadCustomCases(f)
	var objs []*unstructured.Unstructured
	for _, cc := range cases {
		f.Add(cc.crd.json)
		for _, c := range cc.objects {
			objs = append(objs, c.obj)
		}
	}
	for _, c := range loadCases(f, kinds.KeyCustomResourceDefinitions) {
		f.Add(c.json)
	}
	f.Add([]byte(`{"spec":{"group":"a.b","names":{"plural":"p","kind":"K"},"versions":[{"name":"v1","served":true,` +
		`"additionalPrinterColumns":[{"name":"X","type":"integer","jsonPath":"..a[*]"},{"name":"","jsonPath":".a"}]}]},` +
		`"status":{"conditions":[{"type":"Established","status":"True"}]}}`))
	f.Fuzz(func(t *testing.T, data []byte) {
		for _, decode := range []func([]byte, any) error{utiljson.Unmarshal, json.Unmarshal} {
			var m map[string]any
			if decode(data, &m) != nil || m == nil {
				continue
			}
			crd := &unstructured.Unstructured{Object: m}
			k, err := kinds.ParseCRDUnguarded(crd)
			if err != nil {
				continue
			}
			p := k.Profile()
			for _, o := range append(objs, crd) {
				if err := exercise(p, o); err != nil {
					t.Fatal(err)
				}
			}
		}
	})
}

